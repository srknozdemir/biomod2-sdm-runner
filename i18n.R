# Ceviri arama. Anahtar yoksa Ingilizceye, o da yoksa anahtarin kendisine duser.
tr_ <- function(key, lang = "en", ...) {
  lang <- if (is.null(lang) || !(lang %in% names(I18N))) "en" else lang
  v <- I18N[[lang]][[key]]
  if (is.null(v)) v <- I18N[["en"]][[key]]
  if (is.null(v)) return(key)
  dots <- list(...)
  if (length(dots) > 0) return(do.call(sprintf, c(list(v), dots)))
  v
}

# Adlandirilmis secim vektorlerini cevirir: c("key1"="val1") -> c("Ceviri"="val1")
tr_choices <- function(keys, values, lang = "en") {
  stats::setNames(values, vapply(keys, tr_, "", lang = lang))
}
